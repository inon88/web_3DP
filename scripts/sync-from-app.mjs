// Copies the desktop app's pure modules (CommonJS) into src/shared as ES modules, so fixes in the
// desktop app reach the web version with `npm run sync`. Files are regenerated on every run: never edit
// src/shared by hand. The UI files (renderer.js, index.html, styles.css) are copied only when missing
// (or with --ui), because the web version adapts them.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP = path.resolve(WEB, '..');
const SHARED = path.join(WEB, 'src', 'shared');
const MODULES = ['parameters', 'transform', 'heightmap', 'raster-to-svg', 'svg-layers', 'font-name', 'mesh-transform', 'scad-assets', 'image-trace', 'lithophane'];
const UI_FILES = [['renderer.js', 'src/renderer.js'], ['index.html', 'index.html'], ['styles.css', 'src/styles.css']];

function convert(name, source) {
  let code = source.replace(/\r\n/g, '\n');
  // Node-only helper that checks files on disk; the web library checks its own file list.
  if (name === 'scad-assets') {
    code = code.replace(/^const fs = require\('node:fs\/promises'\);\n/m, '').replace(/^const path = require\('node:path'\);\n/m, '');
    code = code.replace(/async function findMissingReferencedAssets[\s\S]*?\n}\n/, '');
    code = code.replace(/,\s*findMissingReferencedAssets/, '');
  }
  // vtracer: the browser build of the same package (scripts/fetch-assets.mjs), initialised by the trace worker.
  if (name === 'image-trace') {
    code = code.replace(/^\s*const vtracer = require\('@visioncortex\/vtracer'\);\n/m, '');
    code = "import * as vtracer from '../vendor/vtracer/vtracer.js';\n" + code;
  }
  code = code.replace(/^const (\w+) = require\('node:crypto'\);$/m, 'const $1 = globalThis.crypto;');
  code = code.replace(/^const (\w+) = require\('node:zlib'\);$/m, "import { zlib as $1 } from '../platform/zlib-shim.js';");
  code = code.replace(/^const (\{[^}]+\}) = require\('\.\/([\w-]+)\.cjs'\);$/gm, (_, names, file) => `import ${names} from './${file}.js';`);
  code = code.replace(/^module\.exports = (\{[\s\S]*?\});?\s*$/m, (_, names) => `export ${names.replace(/\s+/g, ' ')};\n`);
  if (/\bBuffer\b/.test(code)) code = "import { Buffer } from 'buffer';\n" + code;
  const leftover = code.match(/require\([^)]*\)|module\.exports/);
  if (leftover) throw new Error(`${name}.cjs still contains ${leftover[0]} after conversion; extend scripts/sync-from-app.mjs.`);
  return '// Generated by scripts/sync-from-app.mjs from ../' + name + '.cjs — do not edit.\n' + code;
}

await fs.mkdir(SHARED, { recursive: true });
for (const name of MODULES) {
  const source = await fs.readFile(path.join(APP, name + '.cjs'), 'utf8');
  await fs.writeFile(path.join(SHARED, name + '.js'), convert(name, source));
  console.log('synced', name);
}

const forceUi = process.argv.includes('--ui');
for (const [from, to] of UI_FILES) {
  const target = path.join(WEB, to);
  const exists = await fs.access(target).then(() => true, () => false);
  if (exists && !forceUi) { console.log('kept   ', to, '(web-adapted; use --ui to overwrite)'); continue; }
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.copyFile(path.join(APP, from), target);
  console.log('copied ', to);
}
